#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mexico_has_states() {
        assert!(regions_for_country_code("MX").is_some());
        let mx = regions_for_country_code("MX").expect("MX regions");
        assert!(mx.contains(&"Jalisco"));
        assert_eq!(mx.len(), 32);
    }

    #[test]
    fn european_countries_have_regions() {
        for code in [
            "DE", "FR", "IT", "ES", "PL", "NL", "SE", "NO", "CH", "IE", "PT", "GR",
        ] {
            assert!(
                regions_for_country_code(code).is_some(),
                "missing regions for {code}"
            );
        }
    }

    #[test]
    fn unknown_country_has_no_regions() {
        assert!(regions_for_country_code("ZZ").is_none());
    }
}
