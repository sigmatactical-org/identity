//! First-level administrative divisions keyed by ISO 3166-1 alpha-2 country code.
//! Display names are stored in English and persisted as the user's `region` value.

/// Returns first-level regions for `code`, when defined.
#[must_use]
pub fn regions_for_country_code(code: &str) -> Option<&'static [&'static str]> {
    REGIONS_BY_COUNTRY
        .iter()
        .find(|(country, _)| *country == code)
        .map(|(_, regions)| *regions)
}

/// Placeholder label for the region `<select>` on the profile edit form.
#[must_use]
pub fn region_prompt_for_country_code(code: &str) -> &'static str {
    match code {
        "US" => "Select a state…",
        "CA" | "MX" => "Select a province…",
        "CH" => "Select a canton…",
        "GB" => "Select a country…",
        "IE" => "Select a county…",
        "DE" | "AT" => "Select a state…",
        "FR" | "IT" | "ES" | "PL" | "RO" | "UA" | "TR" | "RU" => "Select a region…",
        "NL" | "BE" => "Select a province…",
        _ => "Select a region…",
    }
}

